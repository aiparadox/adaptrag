"""Elements: the typed pieces of content that every extractor produces."""

import re
from enum import StrEnum

from pydantic import BaseModel, Field, field_validator

from adaptrag.core.locators import Locator

NAMESPACED_TYPE = re.compile(r"^[a-z0-9-]+/[a-z0-9_-]+$")


class ElementType(StrEnum):
    """The core vocabulary of element types, shared by every modality."""

    # Structure
    TITLE = "title"
    SECTION_HEADER = "section_header"
    # Text
    PARAGRAPH = "paragraph"
    LIST_ITEM = "list_item"
    CODE = "code"
    FORMULA = "formula"
    FOOTNOTE = "footnote"
    CAPTION = "caption"
    REFERENCE = "reference"
    # Non-text
    TABLE = "table"
    PICTURE = "picture"
    # Furniture: kept, but excluded from chunks
    PAGE_HEADER = "page_header"
    PAGE_FOOTER = "page_footer"
    # Audio
    SPEECH_SEGMENT = "speech_segment"
    SPEAKER_TURN = "speaker_turn"
    TOPIC_SECTION = "topic_section"
    # Model-generated
    DESCRIPTION = "description"
    SUMMARY = "summary"


class Origin(StrEnum):
    """Whether content came from the source or was written by a model."""

    EXTRACTED = "extracted"
    GENERATED = "generated"


CORE_TYPES = {t.value for t in ElementType}


class Element(BaseModel):
    """One typed piece of content from a document, such as a paragraph or table."""

    id: str = Field(
        min_length=1, description="Unique, deterministic ID (see ids.element_id)."
    )
    type: str = Field(
        description=(
            "A core ElementType value, or a namespaced extension such as "
            "'forms/checkbox'. Consumers should treat unknown extensions as text."
        )
    )
    parent_id: str | None = Field(
        default=None, description="ID of the containing element, or None at top level."
    )
    order: int = Field(
        default=0, ge=0, description="Position among siblings, starting at 0."
    )
    text: str | None = Field(
        default=None, description="Text content. None for non-text elements."
    )
    locator: Locator | None = Field(
        default=None,
        description="Where it came from: page and boxes, or a time range.",
    )
    language: str | None = Field(
        default=None, description="Language code of the content, such as 'en'."
    )
    origin: Origin = Field(
        default=Origin.EXTRACTED,
        description="Whether the content was extracted or generated by a model.",
    )
    quality: float | None = Field(
        default=None,
        ge=0,
        le=1,
        description="Extractor confidence from 0 to 1, such as an OCR or ASR score.",
    )
    extractor: str | None = Field(
        default=None, description="Name and version of the extractor that made it."
    )

    @field_validator("type")
    @classmethod
    def _core_or_namespaced(cls, value: str) -> str:
        """Accept core types and namespaced extensions; reject anything else."""
        if value in CORE_TYPES or NAMESPACED_TYPE.match(value):
            return value
        raise ValueError(f"unknown element type: {value!r}")